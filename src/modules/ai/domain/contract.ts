import { z } from 'zod';

/**
 * The response contract v3 (AI_ARCHITECTURE.md §5, §6; ADR-032 + ADR-045).
 *
 * The model finishes every turn by calling `submit_answer` with an object of this shape, and the
 * schema is the first of three gates it must pass — schema, then contract rules (§5), then
 * grounding (§7). What the schema alone buys is that **there is nowhere in the answer for
 * unlabelled, unevidenced text to live** (F-C-05, F-C-06): every sentence the product renders is a
 * `Statement`, and a `Statement` cannot exist without a kind and an evidence list.
 *
 * Three fields are conspicuously ABSENT, and their absence is the point (ADR-045, R2-C-08):
 *
 *   * `EvidenceRef.label` — labels are generated by the server from the referenced object, so a
 *     model cannot write "Verified cash £999,999" into a drawer;
 *   * `confidence.level` — derived by the server as the minimum assurance over cited items, so a
 *     model cannot declare itself confident;
 *   * any prose in `data_quality_notes` — those are enum codes the server renders.
 *
 * Every object is `strictObject`, so a model that sends one of them is a schema failure rather than
 * a silently ignored field.
 */

export const RESPONSE_MODES = ['answer', 'clarification', 'refusal', 'no_data'] as const;
export type ResponseMode = (typeof RESPONSE_MODES)[number];

/** §6. The kind is recomputed by the validator from derived evidence and may only go DOWN (§6.2). */
export const STATEMENT_KINDS = [
  'verified_fact', 'deterministic_calculation', 'estimate', 'inference', 'recommendation',
] as const;
export type StatementKind = (typeof STATEMENT_KINDS)[number];

export const EVIDENCE_REF_TYPES = [
  'metric_snapshot', 'ledger_entry', 'bank_transaction', 'invoice', 'period_balance',
  'counterparty', 'account', 'source_document', 'alert', 'query',
] as const;

export const ENTITY_REF_TYPES = [
  'counterparty', 'account', 'standard_category', 'bank_account',
] as const;

export const UNSUPPORTED_REASONS = [
  'no_data', 'not_in_scope', 'unverified', 'ambiguous_period', 'permission',
] as const;
export type UnsupportedReason = (typeof UNSUPPORTED_REASONS)[number];

const Uuid = z.string().uuid();

export const EvidenceRefSchema = z.strictObject({
  type: z.enum(EVIDENCE_REF_TYPES),
  id: Uuid.optional(),
  revision_no: z.number().int().nonnegative().optional(),
  /** Lower-case hex of the RFC 8785 canonical descriptor (ADR-046.2); never a descriptor object. */
  descriptor_hash: z.string().regex(/^[0-9a-f]{64}$/).optional(),
}).refine(
  (ref) => (ref.type === 'query' ? ref.descriptor_hash !== undefined : ref.id !== undefined),
  { message: 'a query ref carries a descriptor_hash; every other ref carries an id' },
);
export type EvidenceRef = z.infer<typeof EvidenceRefSchema>;

export const EntityRefSchema = z.strictObject({
  type: z.enum(ENTITY_REF_TYPES),
  id: Uuid,
  name: z.string().min(1),
});
export type EntityRef = z.infer<typeof EntityRefSchema>;

/**
 * One numeric claim, bound to the exact tool output it came from.
 *
 * `metric_key` and `entity_id` are what make §7.4 and §7.5 decidable: without them a real number
 * attached to the wrong noun or the wrong customer is indistinguishable from a correct answer,
 * which is how v2 was withdrawn (R2-C-01, R2-C-03).
 */
export const NumberRefSchema = z.strictObject({
  text: z.string().min(1),
  tool_call_seq: z.number().int().nonnegative(),
  path: z.string().min(1),
  metric_key: z.string().min(1).nullable(),
  entity_id: Uuid.nullable(),
});
export type NumberRef = z.infer<typeof NumberRefSchema>;

export const StatementSchema = z.strictObject({
  statement: z.string().min(1),
  kind: z.enum(STATEMENT_KINDS),
  /** Canonical label; §5 requires it whenever the statement contains a number. */
  period: z.string().min(1).nullable(),
  evidence_refs: z.array(EvidenceRefSchema),
  numbers: z.array(NumberRefSchema),
  entity_refs: z.array(EntityRefSchema),
});
export type Statement = z.infer<typeof StatementSchema>;

export const DataQualityNoteSchema = z.strictObject({
  /** An enum value of `data_quality.warnings|missing`; the server renders the prose (R2-C-08). */
  code: z.string().min(1),
  period: z.string().min(1).nullable(),
});

export const RecommendedActionSchema = z.strictObject({
  title: StatementSchema,
  issue: StatementSchema,
  recommendation: StatementSchema,
  priority: z.enum(['critical', 'high', 'medium', 'low']),
});

export const SubmitAnswerSchema = z.strictObject({
  mode: z.enum(RESPONSE_MODES),
  direct_answer: StatementSchema,
  key_findings: z.array(StatementSchema).max(6),
  causes: z.array(StatementSchema).max(5),
  risks: z.array(StatementSchema).max(5),
  opportunities: z.array(StatementSchema).max(5),
  recommended_actions: z.array(RecommendedActionSchema).max(4),
  confidence: z.strictObject({
    data_quality_notes: z.array(DataQualityNoteSchema),
  }),
  evidence: z.array(EvidenceRefSchema),
  unsupported: z.array(z.strictObject({
    topic: z.string().min(1),
    reason: z.enum(UNSUPPORTED_REASONS),
  })),
});
export type SubmitAnswer = z.infer<typeof SubmitAnswerSchema>;

/** Every Statement in an answer, in the order §5 lists them, with a path for the error message. */
export function statementsOf(answer: SubmitAnswer): Array<{ path: string; statement: Statement }> {
  const out: Array<{ path: string; statement: Statement }> = [
    { path: 'direct_answer', statement: answer.direct_answer },
  ];
  const group = (name: keyof SubmitAnswer, list: readonly Statement[]) => {
    list.forEach((statement, index) => out.push({ path: `${String(name)}[${index}]`, statement }));
  };
  group('key_findings', answer.key_findings);
  group('causes', answer.causes);
  group('risks', answer.risks);
  group('opportunities', answer.opportunities);
  answer.recommended_actions.forEach((action, index) => {
    out.push({ path: `recommended_actions[${index}].title`, statement: action.title });
    out.push({ path: `recommended_actions[${index}].issue`, statement: action.issue });
    out.push({ path: `recommended_actions[${index}].recommendation`, statement: action.recommendation });
  });
  return out;
}

/**
 * §6.2: the kind may only be revised DOWNWARD.
 *
 * "If any cited value is `estimate`, the statement is `estimate`." The validator recomputes the
 * kind from the assurance of the items it derives from the statement's `NumberRef`s and overrides
 * the model's label; it never lets the model promote an inference to a verified fact, which is the
 * one direction that would matter to somebody reading a badge.
 */
const KIND_RANK: Readonly<Record<StatementKind, number>> = {
  verified_fact: 4,
  deterministic_calculation: 3,
  estimate: 2,
  inference: 1,
  recommendation: 0,
};

export function weakestKind(a: StatementKind, b: StatementKind): StatementKind {
  return KIND_RANK[a] <= KIND_RANK[b] ? a : b;
}

/** The kind an assurance level supports, before the model's own claim is capped against it (§6). */
export function kindForAssurance(assurance: string): StatementKind {
  if (assurance === 'verified') return 'verified_fact';
  if (assurance === 'calculated') return 'deterministic_calculation';
  return 'estimate';
}
