      references public.source_documents (organization_id, id),
  add constraint ledger_entries_batch_fk foreign key (organization_id, import_batch_id)
      references public.import_batches (organization_id, id),
  add constraint ledger_entries_row_fk foreign key (organization_id, import_row_id)
      references public.import_rows (organization_id, id),
  add constraint ledger_entries_promoted_fk foreign key (organization_id, promoted_from_batch_id)
      references public.import_batches (organization_id, id);

