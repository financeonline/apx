-- MOTION — Phase 2 (plan Phase 4) · Documents and imports.
-- Contract: DATABASE_ARCHITECTURE.md §5; ADR-012, ADR-029.3, ADR-030.2, ADR-033, ADR-038.4,
-- ADR-043.4, ADR-047.3/4/6/10.
--
-- The governing principle for this file is SOW §23: nothing a user uploaded is ever silently
-- discarded. `import_rows` keeps every parsed line forever, including the non-tabular ones, which is
-- why its row count must always equal the count of non-empty source lines.

create table public.source_documents (
  id                    uuid primary key default gen_random_uuid(),
  organization_id       uuid not null references public.organizations (id) on delete cascade,
  storage_bucket        text not null default 'source-documents',
  -- Generated by api_server.register_document as `{org}/{id}/{sanitised filename}` — never supplied
  -- by the caller, so an upload cannot be aimed at another organization's prefix (ADR-043.4).
  storage_path          text not null,
  original_filename     text not null,
  mime_type             text not null,
  byte_size             bigint not null constraint source_documents_size_positive check (byte_size > 0),
  sha256                bytea not null,
  document_kind         public.document_kind_enum not null default 'unknown',
  page_count            integer,
  has_text_layer        boolean,
  extracted_text_path   text,
  status                public.document_status_enum not null default 'uploaded',
  scan_result           jsonb not null default '{}'::jsonb,
  uploaded_by           uuid references public.profiles (id) on delete set null,
  deleted_at            timestamptz,
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now(),
  constraint source_documents_org_id_unique unique (organization_id, id),
  constraint source_documents_object_unique unique (storage_bucket, storage_path)
);

-- CD-12 file-level duplicate: the same bytes cannot be uploaded twice into one organization while
-- the first copy is still live. Restricted to live rows so a deleted document can be re-uploaded.
create unique index source_documents_sha_unique
  on public.source_documents (organization_id, sha256) where deleted_at is null;
create index source_documents_kind_lookup
  on public.source_documents (organization_id, document_kind, created_at desc);

-- Saved column mappings, so the second import of the same report shape asks nothing.
create table public.import_mappings (
  id                 uuid primary key default gen_random_uuid(),
  organization_id    uuid not null references public.organizations (id) on delete cascade,
  name               text not null,
  import_type        public.import_type_enum not null,
  header_signature   text not null,                     -- hash of the normalised header row
  column_map         jsonb not null default '{}'::jsonb,
  transforms         jsonb not null default '{}'::jsonb,
  account_map        jsonb not null default '{}'::jsonb,
  created_by         uuid references public.profiles (id) on delete set null,
  last_used_at       timestamptz,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  constraint import_mappings_org_id_unique unique (organization_id, id),
  constraint import_mappings_signature_unique unique (organization_id, import_type, header_signature)
);

create table public.import_batches (
  id                                uuid primary key default gen_random_uuid(),
  organization_id                   uuid not null references public.organizations (id) on delete cascade,
  source_document_id                uuid not null,
  import_type                       public.import_type_enum not null,
  target_table                      public.import_target_enum not null,
  bank_account_id                   uuid,
  mapping_id                        uuid,
  mapping_snapshot                  jsonb,               -- frozen copy at commit
  status                            public.import_batch_status_enum not null default 'created',
  row_counts                        jsonb not null default '{}'::jsonb,
  -- ADR-047.6: the DECLARED export range, confirmed by the reviewer at IMP-RANGE-015. Coverage tests
  -- read these two columns and never the last posting date, because a quiet month with no
  -- transactions is covered data, not missing data.
  period_start                      date not null,
  period_end                        date not null,
  statement_opening_balance         numeric(18,2),
  statement_closing_balance         numeric(18,2),
  balance_sign                      public.balance_sign_enum not null default 'natural',   -- ADR-047.3
  -- ADR-047.4: the fiscal year in force at commit, frozen. Cumulative differencing must not change
  -- meaning because someone later edited the organization's fiscal year start.
  fiscal_year_start_month_at_commit smallint
    constraint import_batches_fy_month check (fiscal_year_start_month_at_commit between 1 and 12),
  invoice_list_kind                 public.invoice_list_kind_enum,                          -- ADR-047.10
  balance_basis                     public.balance_basis_enum,                              -- ADR-027.1
  extraction_method                 public.extraction_method_enum not null default 'csv',
  pages_extracted                   integer,
  pages_failed                      integer[],                                              -- ADR-033
  created_by                        uuid references public.profiles (id) on delete set null,
  reviewed_by                       uuid references public.profiles (id) on delete set null,
  committed_at                      timestamptz,
  rolled_back_at                    timestamptz,
  rolled_back_reason                text,
  replaced_batch_id                 uuid,                                                   -- ADR-029.3
  error_summary                     jsonb,
  calculation_job_id                uuid,
  calculation_run_id                uuid,   -- set only by the run that actually included the batch
  created_at                        timestamptz not null default now(),
  updated_at                        timestamptz not null default now(),
  constraint import_batches_org_id_unique unique (organization_id, id),
  constraint import_batches_range check (period_end >= period_start),
  constraint import_batches_document_fk
    foreign key (organization_id, source_document_id) references public.source_documents (organization_id, id),
  constraint import_batches_bank_fk
    foreign key (organization_id, bank_account_id) references public.bank_accounts (organization_id, id),
  constraint import_batches_mapping_fk
    foreign key (organization_id, mapping_id) references public.import_mappings (organization_id, id),
  constraint import_batches_replaced_fk
    foreign key (organization_id, replaced_batch_id) references public.import_batches (organization_id, id),
  -- jobs carries `unique (organization_id, id)` for exactly this reason (ADR-044.8).
  constraint import_batches_job_fk
    foreign key (organization_id, calculation_job_id) references public.jobs (organization_id, id) on delete set null,
  constraint import_batches_no_self_replace check (replaced_batch_id is null or replaced_batch_id <> id),
  -- ADR-027.1 / IMP-TB-012: a balance target is meaningless without knowing whether the figures are
  -- cumulative or per-period, so the reviewer must confirm it before the batch can be committed.
  constraint import_batches_basis_required_for_balances
    check (target_table <> 'period_balances' or status not in ('committed') or balance_basis is not null),
  constraint import_batches_bank_target_needs_account
    check (target_table <> 'bank_transactions' or status not in ('committed') or bank_account_id is not null)
);

create index import_batches_status_lookup
  on public.import_batches (organization_id, status, created_at desc);
create index import_batches_document_lookup
  on public.import_batches (organization_id, source_document_id);

create table public.import_rows (
  id                            uuid primary key default gen_random_uuid(),
  organization_id               uuid not null references public.organizations (id) on delete cascade,
  batch_id                      uuid not null,
  row_number                    integer not null,
  source_ref                    text,                    -- sheet!row, or page:line
  -- The file verbatim, including columns nobody mapped. Level-4 evidence highlighting reads it, so
  -- it is never moved or trimmed while the batch is committed.
  raw_data                      jsonb not null default '{}'::jsonb,
  mapped_data                   jsonb,
  status                        public.import_row_status_enum not null default 'pending',
  issues                        jsonb not null default '[]'::jsonb,
  dedupe_hash                   bytea,
  duplicate_of_table            public.financial_record_table_enum,
  duplicate_of_id               uuid,
  duplicate_within_batch_row_id uuid,
  reviewer_decision             public.reviewer_decision_enum not null default 'none',
  reviewer_reason               text,
  committed_table               public.financial_record_table_enum,
  committed_record_id           uuid,
  created_at                    timestamptz not null default now(),
  updated_at                    timestamptz not null default now(),
  constraint import_rows_org_id_unique unique (organization_id, id),
  constraint import_rows_batch_row_unique unique (batch_id, row_number),
  constraint import_rows_batch_fk
    foreign key (organization_id, batch_id) references public.import_batches (organization_id, id) on delete cascade,
  constraint import_rows_within_batch_fk
    foreign key (organization_id, duplicate_within_batch_row_id)
    references public.import_rows (organization_id, id),
  -- A committed row must say both which table it landed in and which row it became, or neither.
  constraint import_rows_committed_pair
    check ((committed_table is null) = (committed_record_id is null)),
  constraint import_rows_duplicate_pair
    check ((duplicate_of_table is null) = (duplicate_of_id is null))
);

create index import_rows_status_lookup on public.import_rows (organization_id, batch_id, status);
create index import_rows_org_dedupe on public.import_rows (organization_id, dedupe_hash);
-- ADR-029.3: rollback looks up the rows of *other* batches that were skipped as duplicates of this
-- batch's rows, so they can be promoted rather than lost.
create index import_rows_duplicate_lookup
  on public.import_rows (organization_id, duplicate_of_table, duplicate_of_id);

-- The four record tables can now point back at the document, batch and row they came from. These are
-- declared here rather than inline above because import_batches/import_rows are created after them.
